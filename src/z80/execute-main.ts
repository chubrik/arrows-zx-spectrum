import { getHLXYd, incPC, next, next16, nop, setPCNext16 } from './utils';

export function executeMain() {

  //#region Inline refresh()
  const r = regs[R];
  regs[R] = (r & BIT7) | ((r + 1) & 0x7F);
  //#endregion

  if (hlt) return;

  //#region Inline next()
  const pcl = regs[PCl];
  const pch = regs[PCh];
  const pc = (pch << 8) | pcl;
  if (pcl === 0xFF) {
    regs[PCl] = 0;
    regs[PCh] = (pch + 1) & 0xFF;
  } else {
    regs[PCl] = pcl + 1;
  }
  const op = mems[pc];
  //#endregion

  opsMain[op]();
}

const opsMain = [
  /* 00 NOP        */ nop,
  /* 01 LD BC,nn   */ () => LD_dd_nn(BC),
  /* 02 LD (BC),A  */ () => write(get16(BC), regs[A]),
  /* 03 INC BC     */ () => set16(BC, (get16(BC) + 1) & 0xFFFF),
  /* 04 INC B      */ () => INC_r(B),
  /* 05 DEC B      */ () => DEC_r(B),
  /* 06 LD B,n     */ () => regs[B] = next(),
  /* 07 RLCA       */ RLCA,
  /* 08 EX AF,AF'  */ EX_AF_AF,
  /* 09 ADD HL,BC  */ () => ADD_HL(BC),
  /* 0A LD A,(BC)  */ () => regs[A] = mems[get16(BC)],
  /* 0B DEC BC     */ () => set16(BC, (get16(BC) - 1) & 0xFFFF),
  /* 0C INC C      */ () => INC_r(C),
  /* 0D DEC C      */ () => DEC_r(C),
  /* 0E LD C,n     */ () => regs[C] = next(),
  /* 0F RRCA       */ RRCA,

  /* 10 DJNZ e     */ DJNZ_e,
  /* 11 LD DE,nn   */ () => LD_dd_nn(DE),
  /* 12 LD (DE),A  */ () => write(get16(DE), regs[A]),
  /* 13 INC DE     */ () => set16(DE, (get16(DE) + 1) & 0xFFFF),
  /* 14 INC D      */ () => INC_r(D),
  /* 15 DEC D      */ () => DEC_r(D),
  /* 16 LD D,n     */ () => regs[D] = next(),
  /* 17 RLA        */ RLA,
  /* 18 JR e       */ JR_e,
  /* 19 ADD HL,DE  */ () => ADD_HL(DE),
  /* 1A LD A,(DE)  */ () => regs[A] = mems[get16(DE)],
  /* 1B DEC DE     */ () => set16(DE, (get16(DE) - 1) & 0xFFFF),
  /* 1C INC E      */ () => INC_r(E),
  /* 1D DEC E      */ () => DEC_r(E),
  /* 1E LD E,n     */ () => regs[E] = next(),
  /* 1F RRA        */ RRA,

  /* 20 JR NZ,e    */ () => fz ? incPC(1) : JR_e(),
  /* 21 LD HL,nn   */ () => LD_dd_nn(HLXY),
  /* 22 LD (nn),HL */ () => write88(next16(), regs[LXY], regs[HXY]),
  /* 23 INC HL     */ () => set16(HLXY, (get16(HLXY) + 1) & 0xFFFF),
  /* 24 INC H      */ () => INC_r(HXY),
  /* 25 DEC H      */ () => DEC_r(HXY),
  /* 26 LD H,n     */ () => regs[HXY] = next(),
  /* 27 DAA        */ DAA,
  /* 28 JR Z,e     */ () => fz ? JR_e() : incPC(1),
  /* 29 ADD HL,HL  */ () => ADD_HL(HLXY),
  /* 2A LD HL,(nn) */ () => { const addr = next16(); set88(HLXY, mems[addr], mems[addr + 1]); },
  /* 2B DEC HL     */ () => set16(HLXY, (get16(HLXY) - 1) & 0xFFFF),
  /* 2C INC L      */ () => INC_r(LXY),
  /* 2D DEC L      */ () => DEC_r(LXY),
  /* 2E LD L,n     */ () => regs[LXY] = next(),
  /* 2F CPL        */ CPL,

  /* 30 JR NC,e    */ () => fc ? incPC(1) : JR_e(),
  /* 31 LD SP,nn   */ () => LD_dd_nn(SP),
  /* 32 LD (nn),A  */ () => write(next16(), regs[A]),
  /* 33 INC SP     */ () => set16(SP, (get16(SP) + 1) & 0xFFFF),
  /* 34 INC (HL)   */ INC_hl,
  /* 35 DEC (HL)   */ DEC_hl,
  /* 36 LD (HL),n  */ () => write(getHLXYd(), next()),
  /* 37 SCF        */ SCF,
  /* 38 JR C,e     */ () => fc ? JR_e() : incPC(1),
  /* 39 ADD HL,SP  */ () => ADD_HL(SP),
  /* 3A LD A,(nn)  */ () => regs[A] = mems[next16()],
  /* 3B DEC SP     */ () => set16(SP, (get16(SP) - 1) & 0xFFFF),
  /* 3C INC A      */ () => INC_r(A),
  /* 3D DEC A      */ () => DEC_r(A),
  /* 3E LD A,n     */ () => regs[A] = next(),
  /* 3F CCF        */ CCF,

  /* 40 LD B,B     */ nop,
  /* 41 LD B,C     */ () => regs[B] = regs[C],
  /* 42 LD B,D     */ () => regs[B] = regs[D],
  /* 43 LD B,E     */ () => regs[B] = regs[E],
  /* 44 LD B,H     */ () => regs[B] = regs[HXY],
  /* 45 LD B,L     */ () => regs[B] = regs[LXY],
  /* 46 LD B,(HL)  */ () => regs[B] = mems[getHLXYd()],
  /* 47 LD B,A     */ () => regs[B] = regs[A],
  /* 48 LD C,B     */ () => regs[C] = regs[B],
  /* 49 LD C,C     */ nop,
  /* 4A LD C,D     */ () => regs[C] = regs[D],
  /* 4B LD C,E     */ () => regs[C] = regs[E],
  /* 4C LD C,H     */ () => regs[C] = regs[HXY],
  /* 4D LD C,L     */ () => regs[C] = regs[LXY],
  /* 4E LD C,(HL)  */ () => regs[C] = mems[getHLXYd()],
  /* 4F LD C,A     */ () => regs[C] = regs[A],

  /* 50 LD D,B     */ () => regs[D] = regs[B],
  /* 51 LD D,C     */ () => regs[D] = regs[C],
  /* 52 LD D,D     */ nop,
  /* 53 LD D,E     */ () => regs[D] = regs[E],
  /* 54 LD D,H     */ () => regs[D] = regs[HXY],
  /* 55 LD D,L     */ () => regs[D] = regs[LXY],
  /* 56 LD D,(HL)  */ () => regs[D] = mems[getHLXYd()],
  /* 57 LD D,A     */ () => regs[D] = regs[A],
  /* 58 LD E,B     */ () => regs[E] = regs[B],
  /* 59 LD E,C     */ () => regs[E] = regs[C],
  /* 5A LD E,D     */ () => regs[E] = regs[D],
  /* 5B LD E,E     */ nop,
  /* 5C LD E,H     */ () => regs[E] = regs[HXY],
  /* 5D LD E,L     */ () => regs[E] = regs[LXY],
  /* 5E LD E,(HL)  */ () => regs[E] = mems[getHLXYd()],
  /* 5F LD E,A     */ () => regs[E] = regs[A],

  /* 60 LD H,B     */ () => regs[HXY] = regs[B],
  /* 61 LD H,C     */ () => regs[HXY] = regs[C],
  /* 62 LD H,D     */ () => regs[HXY] = regs[D],
  /* 63 LD H,E     */ () => regs[HXY] = regs[E],
  /* 64 LD H,H     */ nop,
  /* 65 LD H,L     */ () => regs[HXY] = regs[LXY],
  /* 66 LD H,(HL)  */ () => regs[H] = mems[getHLXYd()],
  /* 67 LD H,A     */ () => regs[HXY] = regs[A],
  /* 68 LD L,B     */ () => regs[LXY] = regs[B],
  /* 69 LD L,C     */ () => regs[LXY] = regs[C],
  /* 6A LD L,D     */ () => regs[LXY] = regs[D],
  /* 6B LD L,E     */ () => regs[LXY] = regs[E],
  /* 6C LD L,H     */ () => regs[LXY] = regs[HXY],
  /* 6D LD L,L     */ nop,
  /* 6E LD L,(HL)  */ () => regs[L] = mems[getHLXYd()],
  /* 6F LD L,A     */ () => regs[LXY] = regs[A],

  /* 70 LD (HL),B  */ () => write(getHLXYd(), regs[B]),
  /* 71 LD (HL),C  */ () => write(getHLXYd(), regs[C]),
  /* 72 LD (HL),D  */ () => write(getHLXYd(), regs[D]),
  /* 73 LD (HL),E  */ () => write(getHLXYd(), regs[E]),
  /* 74 LD (HL),H  */ () => write(getHLXYd(), regs[H]),
  /* 75 LD (HL),L  */ () => write(getHLXYd(), regs[L]),
  /* 76 HALT       */ () => { setHLT(HLT); incPC(-1); },
  /* 77 LD (HL),A  */ () => write(getHLXYd(), regs[A]),
  /* 78 LD A,B     */ () => regs[A] = regs[B],
  /* 79 LD A,C     */ () => regs[A] = regs[C],
  /* 7A LD A,D     */ () => regs[A] = regs[D],
  /* 7B LD A,E     */ () => regs[A] = regs[E],
  /* 7C LD A,H     */ () => regs[A] = regs[HXY],
  /* 7D LD A,L     */ () => regs[A] = regs[LXY],
  /* 7E LD A,(HL)  */ () => regs[A] = mems[getHLXYd()],
  /* 7F LD A,A     */ nop,

  /* 80 ADD A,B    */ () => ADD_ADC(regs[B]),
  /* 81 ADD A,C    */ () => ADD_ADC(regs[C]),
  /* 82 ADD A,D    */ () => ADD_ADC(regs[D]),
  /* 83 ADD A,E    */ () => ADD_ADC(regs[E]),
  /* 84 ADD A,H    */ () => ADD_ADC(regs[HXY]),
  /* 85 ADD A,L    */ () => ADD_ADC(regs[LXY]),
  /* 86 ADD A,(HL) */ () => ADD_ADC(mems[getHLXYd()]),
  /* 87 ADD A,A    */ () => ADD_ADC(regs[A]),
  /* 88 ADC A,B    */ () => ADD_ADC(regs[B], fc),
  /* 89 ADC A,C    */ () => ADD_ADC(regs[C], fc),
  /* 8A ADC A,D    */ () => ADD_ADC(regs[D], fc),
  /* 8B ADC A,E    */ () => ADD_ADC(regs[E], fc),
  /* 8C ADC A,H    */ () => ADD_ADC(regs[HXY], fc),
  /* 8D ADC A,L    */ () => ADD_ADC(regs[LXY], fc),
  /* 8E ADC A,(HL) */ () => ADD_ADC(mems[getHLXYd()], fc),
  /* 8F ADC A,A    */ () => ADD_ADC(regs[A], fc),

  /* 90 SUB B      */ () => SUB_SBC(regs[B]),
  /* 91 SUB C      */ () => SUB_SBC(regs[C]),
  /* 92 SUB D      */ () => SUB_SBC(regs[D]),
  /* 93 SUB E      */ () => SUB_SBC(regs[E]),
  /* 94 SUB H      */ () => SUB_SBC(regs[HXY]),
  /* 95 SUB L      */ () => SUB_SBC(regs[LXY]),
  /* 96 SUB (HL)   */ () => SUB_SBC(mems[getHLXYd()]),
  /* 97 SUB A      */ () => SUB_SBC(regs[A]),
  /* 98 SBC A,B    */ () => SUB_SBC(regs[B], fc),
  /* 99 SBC A,C    */ () => SUB_SBC(regs[C], fc),
  /* 9A SBC A,D    */ () => SUB_SBC(regs[D], fc),
  /* 9B SBC A,E    */ () => SUB_SBC(regs[E], fc),
  /* 9C SBC A,H    */ () => SUB_SBC(regs[HXY], fc),
  /* 9D SBC A,L    */ () => SUB_SBC(regs[LXY], fc),
  /* 9E SBC A,(HL) */ () => SUB_SBC(mems[getHLXYd()], fc),
  /* 9F SBC A,A    */ () => SUB_SBC(regs[A], fc),

  /* A0 AND B      */ () => AND_XOR_OR(regs[A] & regs[B], FH),
  /* A1 AND C      */ () => AND_XOR_OR(regs[A] & regs[C], FH),
  /* A2 AND D      */ () => AND_XOR_OR(regs[A] & regs[D], FH),
  /* A3 AND E      */ () => AND_XOR_OR(regs[A] & regs[E], FH),
  /* A4 AND H      */ () => AND_XOR_OR(regs[A] & regs[HXY], FH),
  /* A5 AND L      */ () => AND_XOR_OR(regs[A] & regs[LXY], FH),
  /* A6 AND (HL)   */ () => AND_XOR_OR(regs[A] & mems[getHLXYd()], FH),
  /* A7 AND A      */ () => AND_XOR_OR(regs[A], FH),
  /* A8 XOR B      */ () => AND_XOR_OR(regs[A] ^ regs[B]),
  /* A9 XOR C      */ () => AND_XOR_OR(regs[A] ^ regs[C]),
  /* AA XOR D      */ () => AND_XOR_OR(regs[A] ^ regs[D]),
  /* AB XOR E      */ () => AND_XOR_OR(regs[A] ^ regs[E]),
  /* AC XOR H      */ () => AND_XOR_OR(regs[A] ^ regs[HXY]),
  /* AD XOR L      */ () => AND_XOR_OR(regs[A] ^ regs[LXY]),
  /* AE XOR (HL)   */ () => AND_XOR_OR(regs[A] ^ mems[getHLXYd()]),
  /* AF XOR A      */ () => AND_XOR_OR(0),

  /* B0 OR B       */ () => AND_XOR_OR(regs[A] | regs[B]),
  /* B1 OR C       */ () => AND_XOR_OR(regs[A] | regs[C]),
  /* B2 OR D       */ () => AND_XOR_OR(regs[A] | regs[D]),
  /* B3 OR E       */ () => AND_XOR_OR(regs[A] | regs[E]),
  /* B4 OR H       */ () => AND_XOR_OR(regs[A] | regs[HXY]),
  /* B5 OR L       */ () => AND_XOR_OR(regs[A] | regs[LXY]),
  /* B6 OR (HL)    */ () => AND_XOR_OR(regs[A] | mems[getHLXYd()]),
  /* B7 OR A       */ () => AND_XOR_OR(regs[A]),
  /* B8 CP B       */ () => CP(regs[B]),
  /* B9 CP C       */ () => CP(regs[C]),
  /* BA CP D       */ () => CP(regs[D]),
  /* BB CP E       */ () => CP(regs[E]),
  /* BC CP H       */ () => CP(regs[HXY]),
  /* BD CP L       */ () => CP(regs[LXY]),
  /* BE CP (HL)    */ () => CP(mems[getHLXYd()]),
  /* BF CP A       */ () => CP(regs[A]),

  /* C0 RET NZ     */ () => fz ? {} : POP_QQ(PC),
  /* C1 POP BC     */ () => POP_QQ(BC),
  /* C2 JP NZ,nn   */ () => fz ? incPC(2) : setPCNext16(),
  /* C3 JP nn      */ () => setPCNext16(),
  /* C4 CALL NZ,nn */ () => fz ? incPC(2) : CALL_cc_nn(),
  /* C5 PUSH BC    */ () => PUSH_QQ(BC),
  /* C6 ADD A,n    */ () => ADD_ADC(next()),
  /* C7 CALL 00h   */ () => CALL_nn(0x00),
  /* C8 RET Z      */ () => fz ? POP_QQ(PC) : {},
  /* C9 RET        */ () => POP_QQ(PC),
  /* CA JP Z,nn    */ () => fz ? setPCNext16() : incPC(2),
  /* CB -- BIT --- */ () => HLXY === HL ? executeBit() : executeBitXYd(),
  /* CC CALL Z,nn  */ () => fz ? CALL_cc_nn() : incPC(2),
  /* CD CALL nn    */ () => CALL_cc_nn(),
  /* CE ADC A,n    */ () => ADD_ADC(next(), fc),
  /* CF CALL 08h   */ () => CALL_nn(0x08),

  /* D0 RET NC     */ () => fc ? {} : POP_QQ(PC),
  /* D1 POP DE     */ () => POP_QQ(DE),
  /* D2 JP NC,nn   */ () => fc ? incPC(2) : setPCNext16(),
  /* D3 OUT (n),A  */ OUT_n_A,
  /* D4 CALL NC,nn */ () => fc ? incPC(2) : CALL_cc_nn(),
  /* D5 PUSH DE    */ () => PUSH_QQ(DE),
  /* D6 SUB A,n    */ () => SUB_SBC(next()),
  /* D7 CALL 10h   */ () => CALL_nn(0x10),
  /* D8 RET C      */ () => fc ? POP_QQ(PC) : {},
  /* D9 EXX        */ EXX,
  /* DA JP C,nn    */ () => fc ? setPCNext16() : incPC(2),
  /* DB IN A,(n)   */ IN_A_n,
  /* DC CALL C,nn  */ () => fc ? CALL_cc_nn() : incPC(2),
  /* DD --- IX --- */ () => { setHLXY(IX); executeMain(); setHLXY(HL); },
  /* DE SBC A,n    */ () => SUB_SBC(next(), fc),
  /* DF CALL 18h   */ () => CALL_nn(0x18),

  /* E0 RET PO     */ () => fp ? {} : POP_QQ(PC),
  /* E1 POP HL     */ () => POP_QQ(HLXY),
  /* E2 JP PO,nn   */ () => fp ? incPC(2) : setPCNext16(),
  /* E3 EX (SP),HL */ EX_sp_HL,
  /* E4 CALL PO,nn */ () => fp ? incPC(2) : CALL_cc_nn(),
  /* E5 PUSH HL    */ () => PUSH_QQ(HLXY),
  /* E6 AND n      */ () => AND_XOR_OR(regs[A] & next(), FH),
  /* E7 CALL 20h   */ () => CALL_nn(0x20),
  /* E8 RET PE     */ () => fp ? POP_QQ(PC) : {},
  /* E9 JP (HL)    */ () => { regs[PCl] = regs[LXY]; regs[PCh] = regs[HXY]; },
  /* EA JP PE,nn   */ () => fp ? setPCNext16() : incPC(2),
  /* EB EX DE,HL   */ EX_DE_HL,
  /* EC CALL PE,nn */ () => fp ? CALL_cc_nn() : incPC(2),
  /* ED -- MISC -- */ executeMisc,
  /* EE XOR n      */ () => AND_XOR_OR(regs[A] ^ next()),
  /* EF CALL 28h   */ () => CALL_nn(0x28),

  /* F0 RET P      */ () => fs ? {} : POP_QQ(PC),
  /* F1 POP AF     */ POP_AF,
  /* F2 JP P,nn    */ () => fs ? incPC(2) : setPCNext16(),
  /* F3 DI         */ () => { setIFF1(0); setIFF2(0); },
  /* F4 CALL P,nn  */ () => fs ? incPC(2) : CALL_cc_nn(),
  /* F5 PUSH AF    */ PUSH_AF,
  /* F6 OR n       */ () => AND_XOR_OR(regs[A] | next()),
  /* F7 RST 30h    */ () => CALL_nn(0x30),
  /* F8 RET M      */ () => fs ? POP_QQ(PC) : {},
  /* F9 LD SP,HL   */ () => { regs[SPl] = regs[LXY]; regs[SPh] = regs[HXY]; },
  /* FA JP M,nn    */ () => fs ? setPCNext16() : incPC(2),
  /* FB EI         */ () => { setIFF1(IFF1); setIFF2(IFF2); setEIDelay(1); },
  /* FC CALL M,nn  */ () => fs ? CALL_cc_nn() : incPC(2),
  /* FD --- IY --- */ () => { setHLXY(IY); executeMain(); setHLXY(HL); },
  /* FE CP n       */ () => CP(next()),
  /* FF CALL 38h   */ () => CALL_nn(0x38),
];
