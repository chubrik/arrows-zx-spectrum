import { xFFFF } from '../common/constants';
import { mem, write, write88 } from '../common/memory';
import { readPort, writePort } from '../common/ports';
import { executeBit } from './execute-bit';
import { executeBitXYd } from './execute-bit-xyd';
import { executeMisc } from './execute-misc';
import { fc, FH, fp, fs, fz, HLT, hlt, IFF1, IFF2, setHLT, setIFF1, setIFF2 } from './flags';
import { RLA, RLCA, RRA, RRCA } from './op/op-bit';
import { DJNZ_e, JR_e, LD_dd_nn, LD_SP_nn } from './op/op-etc';
import { EX_AF_AF, EX_DE_HL, EX_sp_HL, EXX } from './op/op-exchange';
import { ADD_HL } from './op/op-math-16bit';
import { ADD_ADC, AND_XOR_OR, CP, DEC_hl, DEC_r, INC_hl, INC_r, SUB_SBC } from './op/op-math-8bit';
import { CCF, CPL, DAA, SCF } from './op/op-math-etc';
import { RST_p, CALL_nn, POP_AF, RET, POP_QQ, PUSH_AF, PUSH_QQ } from './op/op-stack';
import { A, B, BC, C, cpu, D, DE, E, get16, H, HL, HLXY, HXY, IX, IY, L, LXY, pc, refresh, set16, set88, setEIDelay, setHLXY, setPC, setSP, sp } from './registers';
import { getHLXYd, next, next16, nop, setPCNext16 } from './utils';

export function executeMain() {
  refresh();
  if (hlt) return;
  const op = /*! @__INLINE__ */ next();
  opsMain[op]();
}

const opsMain = [
  /* 00 NOP        */ nop,
  /* 01 LD BC,nn   */ () => LD_dd_nn(BC),
  /* 02 LD (BC),A  */ () => write(get16(BC), cpu[A]),
  /* 03 INC BC     */ () => set16(BC, (get16(BC) + 1) & xFFFF),
  /* 04 INC B      */ () => INC_r(B),
  /* 05 DEC B      */ () => DEC_r(B),
  /* 06 LD B,n     */ () => cpu[B] = next(),
  /* 07 RLCA       */ RLCA,
  /* 08 EX AF,AF'  */ EX_AF_AF,
  /* 09 ADD HL,BC  */ () => ADD_HL(get16(BC)),
  /* 0A LD A,(BC)  */ () => cpu[A] = mem[get16(BC)],
  /* 0B DEC BC     */ () => set16(BC, (get16(BC) - 1) & xFFFF),
  /* 0C INC C      */ () => INC_r(C),
  /* 0D DEC C      */ () => DEC_r(C),
  /* 0E LD C,n     */ () => cpu[C] = next(),
  /* 0F RRCA       */ RRCA,

  /* 10 DJNZ e     */ DJNZ_e,
  /* 11 LD DE,nn   */ () => LD_dd_nn(DE),
  /* 12 LD (DE),A  */ () => write(get16(DE), cpu[A]),
  /* 13 INC DE     */ () => set16(DE, (get16(DE) + 1) & xFFFF),
  /* 14 INC D      */ () => INC_r(D),
  /* 15 DEC D      */ () => DEC_r(D),
  /* 16 LD D,n     */ () => cpu[D] = next(),
  /* 17 RLA        */ RLA,
  /* 18 JR e       */ JR_e,
  /* 19 ADD HL,DE  */ () => ADD_HL(get16(DE)),
  /* 1A LD A,(DE)  */ () => cpu[A] = mem[get16(DE)],
  /* 1B DEC DE     */ () => set16(DE, (get16(DE) - 1) & xFFFF),
  /* 1C INC E      */ () => INC_r(E),
  /* 1D DEC E      */ () => DEC_r(E),
  /* 1E LD E,n     */ () => cpu[E] = next(),
  /* 1F RRA        */ RRA,

  /* 20 JR NZ,e    */ () => fz ? setPC((pc + 1) & xFFFF) : JR_e(),
  /* 21 LD HL,nn   */ () => LD_dd_nn(HLXY),
  /* 22 LD (nn),HL */ () => write88(next16(), cpu[LXY], cpu[HXY]),
  /* 23 INC HL     */ () => set16(HLXY, (get16(HLXY) + 1) & xFFFF),
  /* 24 INC H      */ () => INC_r(HXY),
  /* 25 DEC H      */ () => DEC_r(HXY),
  /* 26 LD H,n     */ () => cpu[HXY] = next(),
  /* 27 DAA        */ DAA,
  /* 28 JR Z,e     */ () => fz ? JR_e() : setPC((pc + 1) & xFFFF),
  /* 29 ADD HL,HL  */ () => ADD_HL(get16(HLXY)),
  /* 2A LD HL,(nn) */ () => { const addr = next16(); set88(HLXY, mem[addr], mem[addr + 1]); },
  /* 2B DEC HL     */ () => set16(HLXY, (get16(HLXY) - 1) & xFFFF),
  /* 2C INC L      */ () => INC_r(LXY),
  /* 2D DEC L      */ () => DEC_r(LXY),
  /* 2E LD L,n     */ () => cpu[LXY] = next(),
  /* 2F CPL        */ CPL,

  /* 30 JR NC,e    */ () => fc ? setPC((pc + 1) & xFFFF) : JR_e(),
  /* 31 LD SP,nn   */ () => LD_SP_nn(),
  /* 32 LD (nn),A  */ () => write(next16(), cpu[A]),
  /* 33 INC SP     */ () => setSP((sp + 1) & xFFFF),
  /* 34 INC (HL)   */ INC_hl,
  /* 35 DEC (HL)   */ DEC_hl,
  /* 36 LD (HL),n  */ () => write(getHLXYd(), next()),
  /* 37 SCF        */ SCF,
  /* 38 JR C,e     */ () => fc ? JR_e() : setPC((pc + 1) & xFFFF),
  /* 39 ADD HL,SP  */ () => ADD_HL(sp),
  /* 3A LD A,(nn)  */ () => cpu[A] = mem[next16()],
  /* 3B DEC SP     */ () => setSP((sp - 1) & xFFFF),
  /* 3C INC A      */ () => INC_r(A),
  /* 3D DEC A      */ () => DEC_r(A),
  /* 3E LD A,n     */ () => cpu[A] = next(),
  /* 3F CCF        */ CCF,

  /* 40 LD B,B     */ nop,
  /* 41 LD B,C     */ () => cpu[B] = cpu[C],
  /* 42 LD B,D     */ () => cpu[B] = cpu[D],
  /* 43 LD B,E     */ () => cpu[B] = cpu[E],
  /* 44 LD B,H     */ () => cpu[B] = cpu[HXY],
  /* 45 LD B,L     */ () => cpu[B] = cpu[LXY],
  /* 46 LD B,(HL)  */ () => cpu[B] = mem[getHLXYd()],
  /* 47 LD B,A     */ () => cpu[B] = cpu[A],
  /* 48 LD C,B     */ () => cpu[C] = cpu[B],
  /* 49 LD C,C     */ nop,
  /* 4A LD C,D     */ () => cpu[C] = cpu[D],
  /* 4B LD C,E     */ () => cpu[C] = cpu[E],
  /* 4C LD C,H     */ () => cpu[C] = cpu[HXY],
  /* 4D LD C,L     */ () => cpu[C] = cpu[LXY],
  /* 4E LD C,(HL)  */ () => cpu[C] = mem[getHLXYd()],
  /* 4F LD C,A     */ () => cpu[C] = cpu[A],

  /* 50 LD D,B     */ () => cpu[D] = cpu[B],
  /* 51 LD D,C     */ () => cpu[D] = cpu[C],
  /* 52 LD D,D     */ nop,
  /* 53 LD D,E     */ () => cpu[D] = cpu[E],
  /* 54 LD D,H     */ () => cpu[D] = cpu[HXY],
  /* 55 LD D,L     */ () => cpu[D] = cpu[LXY],
  /* 56 LD D,(HL)  */ () => cpu[D] = mem[getHLXYd()],
  /* 57 LD D,A     */ () => cpu[D] = cpu[A],
  /* 58 LD E,B     */ () => cpu[E] = cpu[B],
  /* 59 LD E,C     */ () => cpu[E] = cpu[C],
  /* 5A LD E,D     */ () => cpu[E] = cpu[D],
  /* 5B LD E,E     */ nop,
  /* 5C LD E,H     */ () => cpu[E] = cpu[HXY],
  /* 5D LD E,L     */ () => cpu[E] = cpu[LXY],
  /* 5E LD E,(HL)  */ () => cpu[E] = mem[getHLXYd()],
  /* 5F LD E,A     */ () => cpu[E] = cpu[A],

  /* 60 LD H,B     */ () => cpu[HXY] = cpu[B],
  /* 61 LD H,C     */ () => cpu[HXY] = cpu[C],
  /* 62 LD H,D     */ () => cpu[HXY] = cpu[D],
  /* 63 LD H,E     */ () => cpu[HXY] = cpu[E],
  /* 64 LD H,H     */ nop,
  /* 65 LD H,L     */ () => cpu[HXY] = cpu[LXY],
  /* 66 LD H,(HL)  */ () => cpu[H] = mem[getHLXYd()],
  /* 67 LD H,A     */ () => cpu[HXY] = cpu[A],
  /* 68 LD L,B     */ () => cpu[LXY] = cpu[B],
  /* 69 LD L,C     */ () => cpu[LXY] = cpu[C],
  /* 6A LD L,D     */ () => cpu[LXY] = cpu[D],
  /* 6B LD L,E     */ () => cpu[LXY] = cpu[E],
  /* 6C LD L,H     */ () => cpu[LXY] = cpu[HXY],
  /* 6D LD L,L     */ nop,
  /* 6E LD L,(HL)  */ () => cpu[L] = mem[getHLXYd()],
  /* 6F LD L,A     */ () => cpu[LXY] = cpu[A],

  /* 70 LD (HL),B  */ () => write(getHLXYd(), cpu[B]),
  /* 71 LD (HL),C  */ () => write(getHLXYd(), cpu[C]),
  /* 72 LD (HL),D  */ () => write(getHLXYd(), cpu[D]),
  /* 73 LD (HL),E  */ () => write(getHLXYd(), cpu[E]),
  /* 74 LD (HL),H  */ () => write(getHLXYd(), cpu[H]),
  /* 75 LD (HL),L  */ () => write(getHLXYd(), cpu[L]),
  /* 76 HALT       */ () => { setHLT(HLT); setPC(pc - 1); },
  /* 77 LD (HL),A  */ () => write(getHLXYd(), cpu[A]),
  /* 78 LD A,B     */ () => cpu[A] = cpu[B],
  /* 79 LD A,C     */ () => cpu[A] = cpu[C],
  /* 7A LD A,D     */ () => cpu[A] = cpu[D],
  /* 7B LD A,E     */ () => cpu[A] = cpu[E],
  /* 7C LD A,H     */ () => cpu[A] = cpu[HXY],
  /* 7D LD A,L     */ () => cpu[A] = cpu[LXY],
  /* 7E LD A,(HL)  */ () => cpu[A] = mem[getHLXYd()],
  /* 7F LD A,A     */ nop,

  /* 80 ADD A,B    */ () => ADD_ADC(cpu[B]),
  /* 81 ADD A,C    */ () => ADD_ADC(cpu[C]),
  /* 82 ADD A,D    */ () => ADD_ADC(cpu[D]),
  /* 83 ADD A,E    */ () => ADD_ADC(cpu[E]),
  /* 84 ADD A,H    */ () => ADD_ADC(cpu[HXY]),
  /* 85 ADD A,L    */ () => ADD_ADC(cpu[LXY]),
  /* 86 ADD A,(HL) */ () => ADD_ADC(mem[getHLXYd()]),
  /* 87 ADD A,A    */ () => ADD_ADC(cpu[A]),
  /* 88 ADC A,B    */ () => ADD_ADC(cpu[B], fc),
  /* 89 ADC A,C    */ () => ADD_ADC(cpu[C], fc),
  /* 8A ADC A,D    */ () => ADD_ADC(cpu[D], fc),
  /* 8B ADC A,E    */ () => ADD_ADC(cpu[E], fc),
  /* 8C ADC A,H    */ () => ADD_ADC(cpu[HXY], fc),
  /* 8D ADC A,L    */ () => ADD_ADC(cpu[LXY], fc),
  /* 8E ADC A,(HL) */ () => ADD_ADC(mem[getHLXYd()], fc),
  /* 8F ADC A,A    */ () => ADD_ADC(cpu[A], fc),

  /* 90 SUB B      */ () => SUB_SBC(cpu[B]),
  /* 91 SUB C      */ () => SUB_SBC(cpu[C]),
  /* 92 SUB D      */ () => SUB_SBC(cpu[D]),
  /* 93 SUB E      */ () => SUB_SBC(cpu[E]),
  /* 94 SUB H      */ () => SUB_SBC(cpu[HXY]),
  /* 95 SUB L      */ () => SUB_SBC(cpu[LXY]),
  /* 96 SUB (HL)   */ () => SUB_SBC(mem[getHLXYd()]),
  /* 97 SUB A      */ () => SUB_SBC(cpu[A]),
  /* 98 SBC A,B    */ () => SUB_SBC(cpu[B], fc),
  /* 99 SBC A,C    */ () => SUB_SBC(cpu[C], fc),
  /* 9A SBC A,D    */ () => SUB_SBC(cpu[D], fc),
  /* 9B SBC A,E    */ () => SUB_SBC(cpu[E], fc),
  /* 9C SBC A,H    */ () => SUB_SBC(cpu[HXY], fc),
  /* 9D SBC A,L    */ () => SUB_SBC(cpu[LXY], fc),
  /* 9E SBC A,(HL) */ () => SUB_SBC(mem[getHLXYd()], fc),
  /* 9F SBC A,A    */ () => SUB_SBC(cpu[A], fc),

  /* A0 AND B      */ () => AND_XOR_OR(cpu[A] & cpu[B], FH),
  /* A1 AND C      */ () => AND_XOR_OR(cpu[A] & cpu[C], FH),
  /* A2 AND D      */ () => AND_XOR_OR(cpu[A] & cpu[D], FH),
  /* A3 AND E      */ () => AND_XOR_OR(cpu[A] & cpu[E], FH),
  /* A4 AND H      */ () => AND_XOR_OR(cpu[A] & cpu[HXY], FH),
  /* A5 AND L      */ () => AND_XOR_OR(cpu[A] & cpu[LXY], FH),
  /* A6 AND (HL)   */ () => AND_XOR_OR(cpu[A] & mem[getHLXYd()], FH),
  /* A7 AND A      */ () => AND_XOR_OR(cpu[A], FH),
  /* A8 XOR B      */ () => AND_XOR_OR(cpu[A] ^ cpu[B]),
  /* A9 XOR C      */ () => AND_XOR_OR(cpu[A] ^ cpu[C]),
  /* AA XOR D      */ () => AND_XOR_OR(cpu[A] ^ cpu[D]),
  /* AB XOR E      */ () => AND_XOR_OR(cpu[A] ^ cpu[E]),
  /* AC XOR H      */ () => AND_XOR_OR(cpu[A] ^ cpu[HXY]),
  /* AD XOR L      */ () => AND_XOR_OR(cpu[A] ^ cpu[LXY]),
  /* AE XOR (HL)   */ () => AND_XOR_OR(cpu[A] ^ mem[getHLXYd()]),
  /* AF XOR A      */ () => AND_XOR_OR(0),

  /* B0 OR B       */ () => AND_XOR_OR(cpu[A] | cpu[B]),
  /* B1 OR C       */ () => AND_XOR_OR(cpu[A] | cpu[C]),
  /* B2 OR D       */ () => AND_XOR_OR(cpu[A] | cpu[D]),
  /* B3 OR E       */ () => AND_XOR_OR(cpu[A] | cpu[E]),
  /* B4 OR H       */ () => AND_XOR_OR(cpu[A] | cpu[HXY]),
  /* B5 OR L       */ () => AND_XOR_OR(cpu[A] | cpu[LXY]),
  /* B6 OR (HL)    */ () => AND_XOR_OR(cpu[A] | mem[getHLXYd()]),
  /* B7 OR A       */ () => AND_XOR_OR(cpu[A]),
  /* B8 CP B       */ () => CP(cpu[B]),
  /* B9 CP C       */ () => CP(cpu[C]),
  /* BA CP D       */ () => CP(cpu[D]),
  /* BB CP E       */ () => CP(cpu[E]),
  /* BC CP H       */ () => CP(cpu[HXY]),
  /* BD CP L       */ () => CP(cpu[LXY]),
  /* BE CP (HL)    */ () => CP(mem[getHLXYd()]),
  /* BF CP A       */ () => CP(cpu[A]),

  /* C0 RET NZ     */ () => fz ? {} : RET(),
  /* C1 POP BC     */ () => POP_QQ(BC),
  /* C2 JP NZ,nn   */ () => fz ? setPC((pc + 2) & xFFFF) : setPCNext16(),
  /* C3 JP nn      */ () => setPCNext16(),
  /* C4 CALL NZ,nn */ () => fz ? setPC((pc + 2) & xFFFF) : CALL_nn(),
  /* C5 PUSH BC    */ () => PUSH_QQ(BC),
  /* C6 ADD A,n    */ () => ADD_ADC(next()),
  /* C7 RST 00h    */ () => RST_p(0x00),
  /* C8 RET Z      */ () => fz ? RET() : {},
  /* C9 RET        */ () => RET(),
  /* CA JP Z,nn    */ () => fz ? setPCNext16() : setPC((pc + 2) & xFFFF),
  /* CB -- BIT --- */ () => HLXY === HL ? executeBit() : executeBitXYd(),
  /* CC CALL Z,nn  */ () => fz ? CALL_nn() : setPC((pc + 2) & xFFFF),
  /* CD CALL nn    */ () => CALL_nn(),
  /* CE ADC A,n    */ () => ADD_ADC(next(), fc),
  /* CF RST 08h    */ () => RST_p(0x08),
  
  /* D0 RET NC     */ () => fc ? {} : RET(),
  /* D1 POP DE     */ () => POP_QQ(DE),
  /* D2 JP NC,nn   */ () => fc ? setPC((pc + 2) & xFFFF) : setPCNext16(),
  /* D3 OUT (n),A  */ () => writePort(next(), cpu[A], cpu[A]),
  /* D4 CALL NC,nn */ () => fc ? setPC((pc + 2) & xFFFF) : CALL_nn(),
  /* D5 PUSH DE    */ () => PUSH_QQ(DE),
  /* D6 SUB A,n    */ () => SUB_SBC(next()),
  /* D7 RST 10h    */ () => RST_p(0x10),
  /* D8 RET C      */ () => fc ? RET() : {},
  /* D9 EXX        */ EXX,
  /* DA JP C,nn    */ () => fc ? setPCNext16() : setPC((pc + 2) & xFFFF),
  /* DB IN A,(n)   */ () => cpu[A] = readPort(next(), cpu[A]),
  /* DC CALL C,nn  */ () => fc ? CALL_nn() : setPC((pc + 2) & xFFFF),
  /* DD --- IX --- */ () => { setHLXY(IX); executeMain(); setHLXY(HL); },
  /* DE SBC A,n    */ () => SUB_SBC(next(), fc),
  /* DF RST 18h    */ () => RST_p(0x18),

  /* E0 RET PO     */ () => fp ? {} : RET(),
  /* E1 POP HL     */ () => POP_QQ(HLXY),
  /* E2 JP PO,nn   */ () => fp ? setPC((pc + 2) & xFFFF) : setPCNext16(),
  /* E3 EX (SP),HL */ EX_sp_HL,
  /* E4 CALL PO,nn */ () => fp ? setPC((pc + 2) & xFFFF) : CALL_nn(),
  /* E5 PUSH HL    */ () => PUSH_QQ(HLXY),
  /* E6 AND n      */ () => AND_XOR_OR(cpu[A] & next(), FH),
  /* E7 RST 20h    */ () => RST_p(0x20),
  /* E8 RET PE     */ () => fp ? RET() : {},
  /* E9 JP (HL)    */ () => { setPC(cpu[LXY] | (cpu[HXY] << 8)); },
  /* EA JP PE,nn   */ () => fp ? setPCNext16() : setPC((pc + 2) & xFFFF),
  /* EB EX DE,HL   */ EX_DE_HL,
  /* EC CALL PE,nn */ () => fp ? CALL_nn() : setPC((pc + 2) & xFFFF),
  /* ED -- MISC -- */ executeMisc,
  /* EE XOR n      */ () => AND_XOR_OR(cpu[A] ^ next()),
  /* EF RST 28h    */ () => RST_p(0x28),

  /* F0 RET P      */ () => fs ? {} : RET(),
  /* F1 POP AF     */ POP_AF,
  /* F2 JP P,nn    */ () => fs ? setPC((pc + 2) & xFFFF) : setPCNext16(),
  /* F3 DI         */ () => { setIFF1(0); setIFF2(0); },
  /* F4 CALL P,nn  */ () => fs ? setPC((pc + 2) & xFFFF) : CALL_nn(),
  /* F5 PUSH AF    */ PUSH_AF,
  /* F6 OR n       */ () => AND_XOR_OR(cpu[A] | next()),
  /* F7 RST 30h    */ () => RST_p(0x30),
  /* F8 RET M      */ () => fs ? RET() : {},
  /* F9 LD SP,HL   */ () => { setSP(cpu[LXY] | (cpu[HXY] << 8)); },
  /* FA JP M,nn    */ () => fs ? setPCNext16() : setPC((pc + 2) & xFFFF),
  /* FB EI         */ () => { setIFF1(IFF1); setIFF2(IFF2); setEIDelay(1); },
  /* FC CALL M,nn  */ () => fs ? CALL_nn() : setPC((pc + 2) & xFFFF),
  /* FD --- IY --- */ () => { setHLXY(IY); executeMain(); setHLXY(HL); },
  /* FE CP n       */ () => CP(next()),
  /* FF RST 38h    */ () => RST_p(0x38),
];
