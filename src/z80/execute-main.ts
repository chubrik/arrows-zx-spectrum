export function executeMain() {
  executeMainProceed();
}

function executeMainProceed() {
  /*!inline*/
  refresh();
  opsMain[next()]();
}

function jrTaken() { ts(TSTATES_EXTRA_JR); JR_e(); }
function callTaken() { ts(TSTATES_EXTRA_CALL); CALL_nn(); }
function retTaken() { ts(TSTATES_EXTRA_RET); RET(); }

