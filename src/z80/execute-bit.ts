/** Bit Instructions (CB) */
export function executeBit() {
  refresh();
  opsBit[next()]();
}

function testBitVal(bit: number, value: number) {
  BIT_b_r(value & bit, value);
}

function testBit(bit: number) {
  BIT_b_r(mem[getHL()] & bit, wzh);
}

function resBitMem(bit: number, addr: number) {
  write(addr, mem[addr] & bit);
}

function setBitMem(bit: number, addr: number) {
  write(addr, mem[addr] | bit);
}

